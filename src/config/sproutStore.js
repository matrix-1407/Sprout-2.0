const forbiddenCopy = /\b(guaranteed|safe|risk-free|risk free)\b/i;

function collectStrings(value, path = 'copy') {
  if (typeof value === 'string') return [{ path, value }];
  if (!value || typeof value !== 'object') return [];
  return Object.entries(value).flatMap(([key, child]) => collectStrings(child, `${path}.${key}`));
}

export function auditComplianceCopy(copy = sproutCopy) {
  const violations = collectStrings(copy).filter(({ value }) => forbiddenCopy.test(value));
  return { valid: violations.length === 0, violations };
}

export function validatePAN(input = '') {
  const normalized = String(input).toUpperCase().replace(/\s+/g, '');
  const remaining = Math.max(0, 10 - normalized.length);
  const valid = /^[A-Z]{5}[0-9]{4}[A-Z]{1}$/.test(normalized);
  return {
    value: normalized,
    valid,
    characterCount: normalized.length,
    message: valid ? 'Valid PAN format' : `${remaining} character${remaining === 1 ? '' : 's'} remaining`,
  };
}

export function validateMobileLast4(input = '') {
  const value = String(input).replace(/\D/g, '').slice(0, 4);
  return {
    value,
    valid: /^\d{4}$/.test(value),
    characterCount: value.length,
    message: value.length === 4 ? 'Ready for DigiLocker OTP' : `${4 - value.length} digit${value.length === 1 ? '' : 's'} remaining`,
  };
}

